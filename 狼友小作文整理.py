def extract_gdoc_id(url): return re.search(r'/d/([a-zA-Z0-9-_]+)', url).group(1) if re.search(r'/d/([a-zA-Z0-9-_]+)', url) else None

def real_download(url, output_path):
    if "drive.google.com" not in url and "docs.google.com" not in url: return False, "Skip: 非 Google"
    file_id = extract_gdoc_id(url)
    if not file_id: return False, "無效 ID"
    try:
        if "docs.google.com/document" in url:
            resp = requests.get(f"https://docs.google.com/document/d/{file_id}/export?format=txt", timeout=10)
            if resp.status_code == 200:
                with open(output_path, "w", encoding="utf-8") as f: f.write(resp.text)
                return True, "GDocs OK"
            return False, f"Err: {resp.status_code}"
        elif "drive.google.com/file" in url:
            gdown.download(id=file_id, output=output_path, quiet=True, fuzzy=True)
            if os.path.exists(output_path): return True, "GDrive OK"
            return False, "GDrive Fail"
    except Exception as e: return False, str(e)
    return False, "不支援"

