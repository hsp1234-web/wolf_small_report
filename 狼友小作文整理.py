def init_db():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    # 主表
    c.execute('''
    CREATE TABLE IF NOT EXISTS essays (
        id INTEGER PRIMARY KEY,
        link TEXT,
        source_type TEXT,
        original_title TEXT,
        local_text_path TEXT,
        image_count INTEGER DEFAULT 0,
        download_status TEXT DEFAULT 'pending',
        analysis_status TEXT DEFAULT 'pending',
        markdown_status TEXT DEFAULT 'pending',
        error_log TEXT
    )
    ''')

    # 子表
    c.execute('''
    CREATE TABLE IF NOT EXISTS essay_scores (
        essay_id INTEGER PRIMARY KEY,
        target_name TEXT,
        target_code TEXT,
        analysis_score INTEGER,
        analysis_comment TEXT,
        risk_score INTEGER,
        risk_comment TEXT,
        short_summary TEXT
    )
    ''')
    conn.commit()
    return conn

# 4. 從 CSV 匯入資料
def ingest_links():
    if not os.path.exists(LINKS_CSV):
        print(f"❌ 找不到 CSV 檔：{LINKS_CSV}")
        return

    conn = init_db()
    c = conn.cursor()

    print(f"📂 正在讀取 {LINKS_CSV}...")
    try:
        # 強制使用 \t 作為分隔符號
        with open(LINKS_CSV, 'r', encoding='utf-8') as f:
            # 直接指定 delimiter='\t'
            reader = csv.DictReader(f, delimiter='\t')

            count = 0
            new_count = 0
            for row in reader:
                count += 1
                # 簡單防呆，若讀到空行或缺少 id 則跳過
                if not row.get('id'):
                    continue

                eid = int(row['id'])
                link = row.get('link', '')
                src_type = row.get('source_type', 'unknown')
                text = row.get('text', '')

                # 檢查是否已存在
                c.execute("SELECT 1 FROM essays WHERE id = ?", (eid,))
                if c.fetchone() is None:
                    # 插入新資料
                    c.execute('''
                        INSERT INTO essays (id, link, source_type, original_title)
                        VALUES (?, ?, ?, ?)
                    ''', (eid, link, src_type, text))
                    new_count += 1

            conn.commit()
            print(f"✅ 同步完成！CSV 共有 {count} 筆，本次新增入庫: {new_count} 筆。")

    except Exception as e:
        print(f"❌ 匯入失敗: {e}")
        # 印出第一行幫助 debug
        try:
            with open(LINKS_CSV, 'r', encoding='utf-8') as f:
                print(f"檔案首行預覽: {f.readline()}")
        except:
            pass
    finally:
        conn.close()

# 執行匯入
ingest_links()

