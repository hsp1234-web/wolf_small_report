#@title 4. 報告生成器：產出 Markdown (Export to MD)
import sqlite3
import os

# --- 設定路徑 ---
DB_PATH = "/content/drive/MyDrive/wolf_small_report/output/db/wolf_report.db"
MD_DIR = "/content/drive/MyDrive/wolf_small_report/output/md"
os.makedirs(MD_DIR, exist_ok=True)

def generate_markdown_reports():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()

    # 1. 撈取「已分析完成」但「還沒產出 MD」的文章
    # 我們會 join essay_scores 表來拿到 AI 的分析結果
    query = """
        SELECT
            e.id, e.link, e.original_title,
            s.target_name, s.target_code,
            s.analysis_score, s.analysis_comment,
            s.risk_score, s.risk_comment,
            s.short_summary
        FROM essays e
        JOIN essay_scores s ON e.id = s.essay_id
        WHERE e.analysis_status = 'done'
          AND e.markdown_status = 'pending'
    """
    c.execute(query)
    rows = c.fetchall()

    if not rows:
        print("🎉 所有已分析的文章都已生成報告！")
        conn.close()
        return

    print(f"📄 準備生成 {len(rows)} 份 Markdown 報告...")

    for row in rows:
        (eid, link, title, target, code, a_score, a_comment, r_score, r_comment, summary) = row

        # 處理一下可能為 None 的欄位
        target = target if target else "未分類"
        code = code if code else "N/A"
        summary = summary if summary else "無摘要"

        # --- 2. 檔名設計 ---
        # 格式：0006_台積電_2330.md
        safe_target = target.replace("/", "_").replace("\\", "_")
        filename = f"{eid:04d}_{safe_target}_{code}.md"
        filepath = os.path.join(MD_DIR, filename)

        # --- 3. Markdown 內容樣板 ---
        md_content = f"""# {target} ({code}) - 投資分析報告

> **編號**: {eid}
> **原始連結**: [{title}]({link})
> **AI 摘要**: {summary}

---

## 📊 評分總覽
| 面向 | 分數 (1-5) | 評語 |
| :--- | :---: | :--- |
| **分析邏輯** | {a_score} ⭐ | {a_comment} |
| **風險係數** | {r_score} ⚠️ | {r_comment} |

## 📝 詳細分析
(此處為 AI 根據原文的深度解析...)

* **標的**: {target}
* **代碼**: {code}
* **風險提示**: {r_comment}

---
*Generated by Wolf Small Report System*
"""

        # --- 4. 寫檔與更新狀態 ---
        try:
            with open(filepath, "w", encoding="utf-8") as f:
                f.write(md_content)

            # 更新 DB 狀態
            c.execute("UPDATE essays SET markdown_status='done' WHERE id=?", (eid,))
            # 順便記錄 md 檔路徑 (雖然我們剛剛說極簡，但留個紀錄也好)
            # c.execute("UPDATE essay_outputs SET markdown_path=? ...") # 這裡簡化省略

            print(f"✅ 生成: {filename}")

        except Exception as e:
            print(f"❌ 生成失敗 ID {eid}: {e}")

    conn.commit()
    conn.close()
    print("🏁 報告生成完畢！")

if __name__ == "__main__":
    generate_markdown_reports()