def extract_text(path):
    if not os.path.exists(path): return ""
    text = ""
    try:
        with open(path, 'rb') as f: header = f.read(4)
        if header == b'%PDF':
            doc = fitz.open(path)
            for page in doc: text += page.get_text() + "\n"
        else:
            with open(path, 'r', encoding='utf-8', errors='ignore') as f: text = f.read()
    except: return ""
    return text.strip()

