class LogManager:
    def __init__(self, max_lines):
        self.buffer_logs = collections.deque(maxlen=max_lines)
        self.lock = threading.Lock()
    def update_log(self, eid, c_info, r_info, level="INFO"):
        with self.lock:
            found = False; new_buffer = collections.deque(maxlen=self.buffer_logs.maxlen)
            # 嘗試更新現有的 log entry
            for item in self.buffer_logs:
                if item[0] == eid:
                    item = (eid, level, c_info, r_info)
                    found = True
                new_buffer.append(item)
            if not found:
                new_buffer.append((eid, level, c_info, r_info))
            self.buffer_logs = new_buffer
    def get_logs(self):
        with self.lock:
            return list(self.buffer_logs)

class DisplayManager(threading.Thread):
    def __init__(self, stats, log_mgr):
        super().__init__(); self.stats = stats; self.log_mgr = log_mgr; self.running = True; self.daemon = True
    def run(self):
        # 初始清除一次
        clear_output(wait=True)
        while self.running:
            self._refresh()
            time.sleep(0.5) # 降低刷新頻率至 0.5s，減少閃爍

    def _refresh(self):
        logs = self.log_mgr.get_logs()
        status = self.stats.get("status", "待機"); task = self.stats.get("task", "")
        processed = self.stats.get("processed", 0); total = self.stats.get("total", 0)
        unsynced = self.stats.get("unsynced", 0)

        # 構建輸出字串，一次性 print 避免多次 I/O
        output_str = []
        output_str.append(f"📊 Wolf Report v98.1 (Local Mode - Sync every {SYNC_INTERVAL})")
        output_str.append("=" * 80)

        # 只顯示固定行數的 logs
        for eid, level, l1, l2 in logs:
            color = "\033[92m" if level=="SUCCESS" else "\033[91m" if level=="ERROR" else "\033[93m" if level=="BUSY" else "\033[97m"
            # 截斷過長的字串以防換行導致抖動
            l1_short = l1[:75] + "..." if len(l1) > 75 else l1
            l2_short = l2[:75] + "..." if len(l2) > 75 else l2
            output_str.append(f"\033[90m  {l1_short}\033[0m")
            output_str.append(f"{color}  └── {l2_short}\033[0m")
            output_str.append("-" * 40)

        # 補齊空白行以維持畫面高度固定
        current_lines = len(logs) * 3
        target_lines = MAX_LOG_LINES * 3
        if current_lines < target_lines:
            output_str.append("\n" * (target_lines - current_lines))

        cpu = psutil.cpu_percent(); ram = psutil.virtual_memory().percent
        progress = processed / total if total > 0 else 0
        bar_len = 20
        filled_len = int(bar_len * progress)
        bar = "█" * filled_len + "░" * (bar_len - filled_len)

        status_line = f"CPU:{cpu}% | RAM:{ram}% | [{status}] {bar} ({processed}/{total}) | ⚠️ 未同步: {unsynced}"
        output_str.append(status_line)

        # 使用 clear_output(wait=True) 配合一次性 print
        clear_output(wait=True)
        print("\n".join(output_str), end="")

    def stop(self): self.running = False

