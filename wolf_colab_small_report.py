os.makedirs("/content/tmp_samples", exist_ok=True)

def extract_gdoc_id(url: str) -> str:
    # e.g. https://docs.google.com/document/d/<ID>/edit...
    m = re.search(r"/document/d/([^/]+)/", url)
    return m.group(1) if m else ""

def extract_drive_file_id(url: str) -> str:
    # 常見格式：https://drive.google.com/file/d/<ID>/view
    m = re.search(r"/file/d/([^/]+)/", url)
    if m:
        return m.group(1)
    # 其他格式試著從 query string 抓 id 參數
    q = parse_qs(urlparse(url).query)
    if "id" in q:
        return q["id"][0]
    return ""

def simple_download(url: str, dest_path: str):
    resp = requests.get(url, stream=True)
    resp.raise_for_status()
    with open(dest_path, "wb") as f:
        for chunk in resp.iter_content(chunk_size=8192):
            if chunk:
                f.write(chunk)

downloaded = []

for _, row in candidates.iterrows():
    file_id = None
    url = row["link"]
    src_type = row["source_type"]
    eid = int(row["id"])

