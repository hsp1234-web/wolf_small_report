def extract_domain(url: str) -> str:
    try:
        netloc = urlparse(url).netloc
        return netloc.lower()
    except Exception:
        return ""

def classify_source(domain: str) -> str:
    if "docs.google.com" in domain:
        return "gdocs"
    if "drive.google.com" in domain:
        return "gdrive_file"
    if domain in {"reurl.cc", "tinyurl.com", "bit.ly"}:
        return "short_url"
    if domain.endswith(".notion.site") or "notion.so" in domain:
        return "notion"
    if "dropbox.com" in domain:
        return "dropbox"
    if "hackmd.io" in domain:
        return "hackmd"
    if "youtu.be" in domain or "youtube.com" in domain:
        return "youtube"
    if "facebook.com" in domain:
        return "facebook"
    return "other"

# 新增欄位
df["domain"] = df["link"].astype(str).apply(extract_domain)
df["source_type"] = df["domain"].apply(classify_source)

