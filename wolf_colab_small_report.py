#@title 解析 LINE TXT，產生連結清單 links.csv

import os
import re
import csv
from datetime import datetime

PROJECT_ROOT = "/content/drive/MyDrive/wolf_small_report"
RAW_DIR = os.path.join(PROJECT_ROOT, "raw")
OUTPUT_DIR = os.path.join(PROJECT_ROOT, "output")
RAW_FILENAME = "-LINE- 小作文天地的聊天記錄20251205_1652.txt"  #@param {type:"string"}

raw_path = os.path.join(RAW_DIR, RAW_FILENAME)
links_csv_path = os.path.join(OUTPUT_DIR, "links.csv")

url_pattern = re.compile(r"https?://\S+") # Corrected: Removed extra backslash

records = []
current_date = None
pending_line = None  # 暫存「文字在上一行、網址在下一行」的情況

with open(raw_path, "r", encoding="utf-8") as f:
    for line in f:
        line = line.rstrip("\n") # Corrected: Stripping standard newline character

        # 1. 判斷是否為日期行，例如：2025/5/2（週五）
        if re.match(r"^\d{4}/\d{1,2}/\d{1,2}", line): # Corrected: Date regex pattern
            current_date = line.strip()
            pending_line = None
            continue

        if not line.strip():
            continue

        parts = line.split("\t")
        if len(parts) < 3:
            # 可能是只有網址的一行，或其他系統訊息
            # 嘗試從這一行抓網址，若有且有 pending_line，就跟上一行合併
            urls = url_pattern.findall(line)
            if urls and pending_line is not None:
                url = urls[0]
                # Extract author_id from pending_line's author, excluding emojis
                filtered_author_from_pending = re.sub(r'[^一-龥0-9a-zA-Z]', '', pending_line.get("author") or "")
                author_id_from_pending = filtered_author_from_pending[:3]
                rec = {
                    "id": len(records) + 1,
                    "date": pending_line.get("date"),
                    "time": pending_line.get("time"),
                    "author_id": author_id_from_pending,
                    "author": pending_line.get("author"),
                    "text": pending_line.get("text"),
                    "link": url,
                }
                records.append(rec)
                pending_line = None
            continue

        time_str, author_raw, content = parts[0].strip(), parts[1].strip(), parts[2].strip()
        datetime_str = f"{current_date} {time_str}" if current_date else ""
        urls = url_pattern.findall(content)

        # Extract the first three digits for author_id, excluding emojis
        filtered_author_raw = re.sub(r'[^一-龥0-9a-zA-Z]', '', author_raw)
        author_id = filtered_author_raw[:3]

        if urls:
            # 同一行就有網址
            url = urls[0]
            text_without_url = url_pattern.sub("", content).strip()
            rec = {
                "id": len(records) + 1,
                "date": datetime_str,
                "time": time_str,
                "author_id": author_id,
                "author": author_raw,
                "text": text_without_url,
                "link": url,
            }
            records.append(rec)
            pending_line = None
        else:
            # 沒有網址，先暫存，有可能下一行才是純網址
            pending_line = {
                "date": datetime_str,
                "time": time_str,
                "author": author_raw,
                "text": content,
            }

# 將結果寫入 CSV，id 就是你要的 name（編號）
fieldnames = ["id", "date", "time", "author_id", "author", "text", "link"]
os.makedirs(OUTPUT_DIR, exist_ok=True)

with open(links_csv_path, "w", encoding="utf-8", newline="") as csvfile:
    writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
    writer.writeheader()
    for rec in records:
        writer.writerow(rec)

print(f"共解析出 {len(records)} 筆連結，已寫入：{links_csv_path}")

print("\n前 10 筆預覽：")
for rec in records[:10]:
    print(
        f"{rec['id']:3d} | {rec['date']} | {rec['author_id']} | {rec['author']} | "
        f"text={rec['text'][:30]} | link={rec['link']}"
    )

